"""Regenerate the committed Python dependency locks (T-033).

Each `requirements*.txt` declares intent as version ranges. Each matching `*.lock` is the exact
resolution installers consume: every transitive package pinned with `==`, platform markers kept,
and sha256 hashes for every distribution so `pip install --require-hashes` can verify downloads.

Resolution is *universal*: one file valid on Windows, Linux and macOS, rather than a freeze of
whichever machine ran this script. By default the resolver is additionally constrained to the
versions installed in the environment running this script, so regenerating a lock records the
versions the test suite actually exercised instead of silently upgrading them. Use `--upgrade`
to deliberately take the newest versions the ranges allow, then run the suite again. The
optional evaluation set is always resolved unconstrained, because this project neither
installs nor exercises those packages; its lock says so in a header comment.

Requires `uv`, which is only a maintenance tool and is deliberately not a project dependency.
Install it into a throwaway environment so the project environment stays untouched:

    python -m venv /tmp/lockenv
    /tmp/lockenv/bin/python -m pip install uv
    /tmp/lockenv/bin/python -m uv --version

Then run this script with `--uv /tmp/lockenv/bin/python` (or put `uv` on PATH).

    python scripts/lock_dependencies.py --uv /tmp/lockenv/bin/python
    python scripts/lock_dependencies.py --check          # CI: fail if a lock is stale
    python scripts/lock_dependencies.py --upgrade        # deliberate version bump
    python scripts/lock_dependencies.py --only evaluation

This script never installs anything and never writes outside the repository root.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Source manifest -> committed lock. `evaluation` is optional and separately installable.
TARGETS = {
    "runtime": ("requirements.txt", "requirements.lock"),
    "dev": ("requirements-dev.txt", "requirements-dev.lock"),
    "evaluation": ("requirements-evaluation.txt", "requirements-evaluation.lock"),
}

#: Sets whose packages this project does not install or exercise, so there is no tested version
#: set to constrain against. They resolve to the newest versions the ranges allow and their lock
#: is labelled unverified.
UNCONSTRAINED = {"evaluation"}

#: Resolve for the oldest interpreter the project supports, so the lock stays valid on newer ones.
PYTHON_VERSION = "3.12"

HEADER = (
    "# Generated by scripts/lock_dependencies.py. Do not edit by hand.\n"
    "# Source: {source}\n"
    "# Universal resolution for Python {python} and newer on Windows, Linux and macOS.\n"
    "# Install with: python -m pip install --require-hashes -r {lock}\n"
)

UNVERIFIED_NOTE = (
    "# Unverified: these optional packages are not installed or exercised by this project's\n"
    "# tests, so the resolution is the newest the ranges allow, not a tested version set.\n"
)

PINNED = re.compile(r"^[A-Za-z0-9._-]+==[0-9][^\s\\]*")


def uv_command(explicit: str | None) -> list[str]:
    """Return the argv prefix that runs uv, preferring an explicitly supplied interpreter."""
    if explicit:
        path = Path(explicit)
        if not path.exists():
            raise SystemExit(f"--uv path does not exist: {explicit}")
        return [str(path), "-m", "uv"]
    found = shutil.which("uv")
    if found:
        return [found]
    raise SystemExit(
        "uv was not found. Install it in a throwaway environment and pass --uv "
        "<that environment's python>; see the module docstring."
    )


def installed_versions() -> str:
    """`name==version` lines for this interpreter, used only to constrain the resolution."""
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        capture_output=True,
        text=True,
        check=True,
    )
    return "\n".join(line for line in result.stdout.splitlines() if PINNED.match(line)) + "\n"


def compile_lock(uv: list[str], source: Path, upgrade: bool) -> str:
    """Resolve one manifest and return the lock text, without writing it anywhere."""
    command = uv + [
        "pip",
        "compile",
        str(source),
        "--universal",
        "--generate-hashes",
        "--python-version",
        PYTHON_VERSION,
        "--no-header",
        # Annotations would record the absolute path of the temporary constraints file.
        "--no-annotate",
    ]
    with tempfile.TemporaryDirectory() as work:
        if not upgrade:
            constraints = Path(work) / "tested-versions.txt"
            constraints.write_text(installed_versions(), encoding="utf-8")
            command += ["--constraint", str(constraints)]
        result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(f"uv pip compile failed for {source.name}:\n{result.stderr}")
    return result.stdout


def render(source: Path, lock: Path, body: str, verified: bool) -> str:
    head = HEADER.format(source=source.name, python=PYTHON_VERSION, lock=lock.name)
    if not verified:
        head += UNVERIFIED_NOTE
    return head + "\n" + body.replace("\r\n", "\n").strip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--uv", help="Interpreter that has uv installed, or omit to use PATH.")
    parser.add_argument(
        "--only", choices=sorted(TARGETS), action="append", help="Limit to one dependency set."
    )
    parser.add_argument(
        "--upgrade",
        action="store_true",
        help="Take the newest versions the ranges allow instead of the installed ones.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report whether the committed locks match a fresh resolution; write nothing.",
    )
    args = parser.parse_args(argv)
    uv = uv_command(args.uv)
    names = args.only or sorted(TARGETS)
    stale = []
    for name in names:
        source_name, lock_name = TARGETS[name]
        source, lock = ROOT / source_name, ROOT / lock_name
        if not source.exists():
            raise SystemExit(f"Missing manifest: {source_name}")
        unconstrained = args.upgrade or name in UNCONSTRAINED
        text = render(
            source, lock, compile_lock(uv, source, unconstrained), name not in UNCONSTRAINED
        )
        current = lock.read_text(encoding="utf-8") if lock.exists() else ""
        if args.check:
            state = "current" if current == text else "STALE"
            if current != text:
                stale.append(lock_name)
            print(f"{lock_name}: {state}")
            continue
        if current == text:
            print(f"{lock_name}: unchanged")
            continue
        lock.write_text(text, encoding="utf-8", newline="\n")
        packages = sum(bool(PINNED.match(line)) for line in text.splitlines())
        print(f"{lock_name}: written ({packages} packages)")
    if stale:
        print(
            "Stale locks: " + ", ".join(stale) + ". Re-run without --check to regenerate.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
